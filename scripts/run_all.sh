#!/usr/bin/env bash
# Reproduce every number in BENCHMARK.md.
#
#   scripts/download_beir.sh scifact nfcorpus fiqa scidocs trec-covid
#   scripts/run_all.sh                # all datasets
#   scripts/run_all.sh scifact fiqa   # subset
#
# Writes (all under results/):
#   ENVIRONMENT.txt              machine, toolchain, git commit
#   summary.tsv                  one line per (dataset, config): metrics + timings
#   <dataset>/<tag>.json         full report incl. per-repeat timings, per-query metrics
#   logs/<dataset>.<tag>.log     raw stderr/stdout of each run
#   crosscheck/<dataset>.<tag>.txt  strata metrics vs pytrec_eval
#   parity/<dataset>.txt         strata vs tantivy ranking comparison
#   memory.tsv                   allocator-measured index heap size
# Run files go to results/runs/ (gitignored, regenerated by this script).
set -euo pipefail
cd "$(dirname "$0")/.."
export PATH="$HOME/.cargo/bin:$PATH"

DATASETS=("$@")
[ ${#DATASETS[@]} -eq 0 ] && DATASETS=(scifact nfcorpus fiqa scidocs trec-covid)
REPEATS=${REPEATS:-3}
R=results
mkdir -p $R/logs $R/crosscheck $R/parity

cargo build --release -q -p strata-eval -p strata-bench
EVAL=target/release/strata-eval
BENCH=target/release/strata-bench
MEM=target/release/strata-mem

{
  echo "date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "git: $(git rev-parse --short HEAD)$(git diff --quiet || echo ' (dirty)')"
  echo "rustc: $(rustc -V)"
  echo "cargo: $(cargo -V)"
  echo "os: $(sw_vers -productName) $(sw_vers -productVersion) ($(uname -m))"
  echo "cpu: $(sysctl -n machdep.cpu.brand_string), $(sysctl -n hw.ncpu) cores ($(sysctl -n hw.perflevel0.physicalcpu 2>/dev/null || echo ?) performance + $(sysctl -n hw.perflevel1.physicalcpu 2>/dev/null || echo ?) efficiency)"
  echo "memory: $(( $(sysctl -n hw.memsize) / 1024 / 1024 / 1024 )) GiB"
  echo "tantivy: $(grep -A1 'name = "tantivy"' Cargo.lock | grep version | head -1 | cut -d'"' -f2)"
  echo "build: cargo --release (opt-level 3, debug=1), single-threaded indexing and search"
} > $R/ENVIRONMENT.txt
cat $R/ENVIRONMENT.txt

# Header written only once so subset re-runs append.
[ -f $R/summary.tsv ] || echo -e "dataset\ttag\tnDCG@10\tR@100\tR@1000\tMRR@10\tdocs/s\tp50(k=1000)\tp99(k=1000)\tp50(k=10)\tp99(k=10)" > $R/summary.tsv

strata() { # dataset tag-args...
  local d=$1; shift
  local out
  out=$($EVAL run --dataset "$d" --repeats "$REPEATS" "$@" 2> >(tee /dev/stderr > $R/logs/tmp.log))
  local tag; tag=$(echo "$out" | cut -f2)
  { cat $R/logs/tmp.log; echo "$out"; } > "$R/logs/$d.$tag.log"
  echo "$out" | tee -a $R/summary.tsv
}

tantivy() { # dataset tokenizer
  local d=$1 tok=$2
  local out
  out=$($BENCH tantivy --dataset "$d" --tokenizer "$tok" --repeats "$REPEATS" 2> >(tee /dev/stderr > $R/logs/tmp.log))
  local tag; tag=$(echo "$out" | cut -f2)
  { cat $R/logs/tmp.log; echo "$out"; } > "$R/logs/$d.$tag.log"
  echo "$out" | tee -a $R/summary.tsv
}

crosscheck() { # dataset tag
  local d=$1 tag=$2
  local run=$R/runs/$d/$tag.trec
  $EVAL eval --dataset "$d" --run "$run" > $R/logs/tmp.json
  uv run -q --with pytrec_eval==0.5 --with numpy python scripts/crosscheck_pytrec.py \
    --qrels "data/$d/qrels/test.tsv" --run "$run" --ours $R/logs/tmp.json | tee "$R/crosscheck/$d.$tag.txt"
}

for d in "${DATASETS[@]}"; do
  echo "=================== $d"
  strata "$d"                                   # default: k1=0.9 b=0.4, exact lengths, Porter
  strata "$d" --doc-length lucene               # Anserini-parity mode
  strata "$d" --k1 1.2 --b 0.75
  strata "$d" --k1 1.2 --b 0.75 --doc-length lucene   # Tantivy-parity mode
  strata "$d" --stemmer porter2                 # ablations
  strata "$d" --stemmer none
  strata "$d" --stopwords none
  tantivy "$d" strata
  tantivy "$d" native

  crosscheck "$d" strata.k1_0.9.b_0.4.exactlen.porter.lucenestop
  crosscheck "$d" tantivy-0.27.0.strata-analyzer

  {
    echo "strata (k1=1.2 b=0.75, Lucene-quantized lengths) vs tantivy 0.27 (strata analyzer)"
    for depth in 10 100; do
      python3 -I scripts/compare_runs.py --depth $depth \
        "$R/runs/$d/strata.k1_1.2.b_0.75.lucenelen.porter.lucenestop.trec" \
        "$R/runs/$d/tantivy-0.27.0.strata-analyzer.trec"
    done
  } | tee "$R/parity/$d.txt"
done
rm -f $R/logs/tmp.log $R/logs/tmp.json

$MEM --datasets "${DATASETS[@]}" | tee $R/memory.tsv
